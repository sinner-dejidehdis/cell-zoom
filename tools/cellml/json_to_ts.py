"""Write src/sim/muscle/shorten2007.ts from the JSON made by cellml_to_json.py (JS mode).

The stimulus current I_HH, a fixed pulse train in the CellML file, is replaced by an argument, so the
page can stimulate whenever the user asks. Everything else is the published model, unchanged.
Run: python tools/cellml/json_to_ts.py model_js.json rest.json src/sim/muscle/shorten2007.ts
"""
import json, re, sys

m = json.load(open(sys.argv[1]))
rest = json.load(open(sys.argv[2]))
names = [s for s, _ in m['states']]
idx = {n: i for i, n in enumerate(names)}
lines = []
lines.append('// GENERATED by tools/cellml/json_to_ts.py from the CellML model of')
lines.append('// Shorten, O\'Callaghan, Davidson, Soboleva (2007) J Muscle Res Cell Motil 28:293-313,')
lines.append('// "A mathematical model of fatigue in skeletal muscle force contraction" (mouse fast-twitch fibre).')
lines.append('// Source: https://models.cellml.org/exposure/159ba2f081022ca651284404f39eeb40  - do not edit by hand.')
lines.append('// Units: time ms, voltage mV, concentrations uM (Ca, Mg, ATP, P) or mM (Na, K), current uA/cm2.')
lines.append('')
lines.append(f'export const N = {len(names)};')
lines.append('export const STATE_NAMES = ' + json.dumps(names) + ' as const;')
lines.append('export const IDX = {' + ', '.join(f'{n}: {i}' for i, n in enumerate(names)) + '} as const;')
lines.append('/** The published initial values, after 3 s without stimulation (the published values are not a rest state). */')
lines.append('export const REST = new Float64Array(' + json.dumps([float(x) for x in rest]) + ');')
lines.append('/** Stimulus amplitude and width used in the paper\'s CellML file (uA/cm2, ms). */')
lines.append('export const STIM_AMPLITUDE = 150;')
lines.append('export const STIM_WIDTH = 0.5;')
lines.append('')
lines.append('/** dy/dt at time t (ms) for state y, with stimulus current stim (uA/cm2). */')
lines.append('export function rates(t: number, y: Float64Array, dy: Float64Array, stim: number): void {')
lines.append(f'  const {m["time"]} = t;')
lines.append(f'  void {m["time"]};')
for k, v in m['consts'].items():
    lines.append(f'  const {k} = {v};')
for i, n in enumerate(names):
    lines.append(f'  const {n} = y[{i}];')
for n, e in m['alg']:
    if n == 'wal_environment__I_HH':
        e = 'stim'
    lines.append(f'  const {n} = {e};')
for i, (n, e) in enumerate(m['odes']):
    assert idx[n] == i
    lines.append(f'  dy[{i}] = {e};')
lines.append('}')
src = '\n'.join(lines) + '\n'
# Python-style power is fine in JS (**), but unary minus before ** is a syntax error: wrap it.
src = re.sub(r'\(-([A-Za-z_0-9]+)\)\*\*', r'((-\1))**', src)
open(sys.argv[3], 'w').write('/* eslint-disable */\n// @ts-nocheck - generated straight-line code with unused constants\n' + src)
print('wrote', sys.argv[3], len(names), 'states')
